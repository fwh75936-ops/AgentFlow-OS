import Phaser from "phaser";
import { TILE, WORLD_W, WORLD_H, FURNITURE, DESKS, WORKSTATIONS, nearestWalkable, STUDIO_VIEW, COMPUTER_ZONE } from "./OfficeMap";
import officeBgFlatUrl from "../../../assets/office-bg-gpt.png";
import officeBgIsoUrl from "../../../assets/office-bg-iso.png";
import { AgentSprite, type DeskZone } from "./AgentSprite";
import type { AgentVisual, AssignmentEvent, StudioCallbacks } from "../types/studio";
import type { TilePoint } from "./Pathfinding";

interface WorkstationSlotView {
  chairTile: TilePoint;
  agentId: number | null;
}

export class OfficeScene extends Phaser.Scene {
  private sprites = new Map<number, AgentSprite>();
  /** Per-employee workstation bindings by zone, in floor-plan order.
   * The desks and chairs themselves are painted into the backdrop; a
   * slot only records which painted chair tile belongs to which real
   * agent. */
  private slotsByZone: Record<string, WorkstationSlotView[]> = {};
  private callbacks: StudioCallbacks | null = null;
  private assignmentQueue: AssignmentEvent[] = [];
  private assignmentBusy = false;
  private pendingVisuals: AgentVisual[] | null = null;
  private ready = false;
  private userZoomed = false;

  constructor() {
    super("office");
  }

  setCallbacks(cb: StudioCallbacks) {
    this.callbacks = cb;
  }

  preload() {
    // The painted backdrop: generated by the user's own GPT image model
    // from the user's reference illustration (all text removed), grid
    // calibration in OfficeMap. It is the ONLY environment art — there
    // is no procedural fallback painting. STUDIO_VIEW (OfficeMap)
    // selects the slanted oblique plate or the previous flat floor
    // plan; both stay in the bundle so the switch is one constant.
    this.load.image("office-bg-img", STUDIO_VIEW === "iso" ? officeBgIsoUrl : officeBgFlatUrl);
  }

  create() {
    if (this.textures.exists("office-bg-img")) {
      this.add.image(0, 0, "office-bg-img").setOrigin(0, 0)
        .setDisplaySize(WORLD_W, WORLD_H).setDepth(0);
    }
    // Fixed furniture is painted into the backdrop (OfficeMap holds its
    // collision footprints), so nothing is rendered for it here — only
    // invisible click zones on the pieces that used to be clickable.
    for (const f of FURNITURE) {
      const zoneType = f.type === "whiteboard" ? "board"
        : f.type === "test_screen" ? "test"
        : f.type === "meeting_table" ? "meeting" : null;
      if (!zoneType) continue;
      const z = this.add.zone(
        (f.x + f.w / 2) * TILE, (f.y + f.h / 2) * TILE, f.w * TILE, f.h * TILE,
      );
      z.setInteractive({ useHandCursor: true });
      let downPos = { x: 0, y: 0 };
      z.on("pointerdown", (p: Phaser.Input.Pointer) => { downPos = { x: p.x, y: p.y }; });
      z.on("pointerup", (p: Phaser.Input.Pointer) => {
        if (Math.hypot(p.x - downPos.x, p.y - downPos.y) <= 6) {
          this.callbacks?.onZoneClick(zoneType);
        }
      });
    }
    // The painted dev workstations double as the shared-computer click
    // target (tile rect per view, from OfficeMap).
    const computerZone = this.add.zone(
      (COMPUTER_ZONE.x + COMPUTER_ZONE.w / 2) * TILE,
      (COMPUTER_ZONE.y + COMPUTER_ZONE.h / 2) * TILE,
      COMPUTER_ZONE.w * TILE, COMPUTER_ZONE.h * TILE,
    );
    computerZone.setInteractive({ useHandCursor: true });
    let cDown = { x: 0, y: 0 };
    computerZone.on("pointerdown", (p: Phaser.Input.Pointer) => { cDown = { x: p.x, y: p.y }; });
    computerZone.on("pointerup", (p: Phaser.Input.Pointer) => {
      if (Math.hypot(p.x - cDown.x, p.y - cDown.y) <= 6) this.callbacks?.onZoneClick("computer");
    });
    // Per-employee workstations: the desks and chairs are painted into
    // the backdrop, so a slot is just a binding record — its painted
    // chair tile, handed to whichever real agent syncAgents assigns.
    for (const [zone, list] of Object.entries(WORKSTATIONS)) {
      this.slotsByZone[zone] = list.map((slot) => ({
        chairTile: { x: slot.chair.x, y: slot.chair.y },
        agentId: null,
      }));
    }
    // No zone name plates and no name tags inside the scene (user rule):
    // zones read from floor material + furniture; names are a DOM overlay.
    const cam = this.cameras.main;
    cam.setBounds(0, 0, WORLD_W, WORLD_H);
    cam.setBackgroundColor("#E7E7E2");
    this.fitCamera();
    // The canvas resizes with the window (Scale.RESIZE): keep the whole
    // office fitted until the user deliberately zooms/pans.
    this.scale.on("resize", () => {
      if (!this.userZoomed) this.fitCamera();
    });
    // Wheel zoom (smooth, clamped, pixel-crisp rendering is set in game config)
    this.input.on("wheel", (_p: Phaser.Input.Pointer, _o: unknown, _dx: number, dy: number) => {
      this.userZoomed = true;
      const zoom = Phaser.Math.Clamp(cam.zoom - Math.sign(dy) * 0.12, 0.6, 2.6);
      cam.zoomTo(140, zoom);
    });
    // Drag pan (click-vs-drag is disambiguated inside AgentSprite)
    let dragStart: { x: number; y: number; sx: number; sy: number } | null = null;
    this.input.on("pointerdown", (p: Phaser.Input.Pointer) => {
      dragStart = { x: p.x, y: p.y, sx: cam.scrollX, sy: cam.scrollY };
    });
    this.input.on("pointermove", (p: Phaser.Input.Pointer) => {
      if (!dragStart || !p.isDown) return;
      if (Math.hypot(p.x - dragStart.x, p.y - dragStart.y) > 6) this.userZoomed = true;
      cam.scrollX = dragStart.sx - (p.x - dragStart.x) / cam.zoom;
      cam.scrollY = dragStart.sy - (p.y - dragStart.y) / cam.zoom;
    });
    this.input.on("pointerup", () => { dragStart = null; });
    this.ready = true;
    if (this.pendingVisuals) {
      this.syncAgents(this.pendingVisuals);
      this.pendingVisuals = null;
    }
  }

  /* ------------------------------------------------------------ cameras -- */

  fitCamera() {
    this.userZoomed = false;
    const cam = this.cameras.main;
    const zoom = Math.min(cam.width / WORLD_W, cam.height / WORLD_H);
    cam.setZoom(Math.max(0.5, zoom));
    cam.centerOn(WORLD_W / 2, WORLD_H / 2);
  }

  resetCamera() {
    this.fitCamera();
  }

  zoomBy(factor: number) {
    this.userZoomed = true;
    const cam = this.cameras.main;
    cam.zoomTo(140, Phaser.Math.Clamp(cam.zoom * factor, 0.6, 2.6));
  }

  focusAgent(agentId: number) {
    const s = this.sprites.get(agentId);
    if (!s) return;
    this.userZoomed = true;
    const cam = this.cameras.main;
    if (cam.zoom < 1.25) cam.zoomTo(200, 1.4);
    cam.pan(s.container.x, s.container.y, 240, "Sine.easeInOut");
  }

  /* -------------------------------------------------------------- agents -- */

  syncAgents(visuals: AgentVisual[]) {
    if (!this.ready) {
      this.pendingVisuals = visuals;
      return;
    }
    const seen = new Set<number>();
    const sorted = [...visuals].sort((a, b) => a.agentId - b.agentId);
    // Bind workstations FROM THE ROSTER: within each zone, agents sorted
    // by id take the zone's slots in floor-plan order — one dedicated
    // painted desk per real employee, stable across polls. Agents beyond
    // the slot count (roster outgrew the floor plan) fall back to meeting
    // seats so nobody is ever left standing without a place.
    for (const entries of Object.values(this.slotsByZone)) {
      for (const e of entries) e.agentId = null;
    }
    const assignment = new Map<number, { desk: TilePoint; zone: DeskZone }>();
    const nextSlot: Record<string, number> = {};
    let meetingIdx = 0;
    let restIdx = 0;
    for (const v of sorted) {
      seen.add(v.agentId);
      if (v.isChief) {
        assignment.set(v.agentId, { desk: DESKS.chief, zone: "chief" });
        continue;
      }
      const entries = this.slotsByZone[v.zone];
      const i = nextSlot[v.zone] ?? 0;
      nextSlot[v.zone] = i + 1;
      if (entries && i < entries.length) {
        entries[i].agentId = v.agentId;
        assignment.set(v.agentId, { desk: entries[i].chairTile, zone: v.zone });
      } else {
        const seat = DESKS.meeting[meetingIdx++ % DESKS.meeting.length];
        assignment.set(v.agentId, { desk: seat, zone: v.zone });
      }
    }
    for (const v of sorted) {
      const { desk, zone } = assignment.get(v.agentId)!;
      const rest = DESKS.rest[(restIdx++) % DESKS.rest.length];
      const existing = this.sprites.get(v.agentId);
      if (existing) {
        existing.desk = desk;
        existing.deskZone = zone;
        existing.restSpot = rest;
        existing.isChief = v.isChief;
        existing.applyVisual(v);
      } else {
        const spawn = nearestWalkable(desk.x, desk.y);
        const sprite = new AgentSprite(
          this, v, desk, zone, rest, v.isChief, spawn,
          (id) => this.callbacks?.onSelectAgent(id),
          (id) => this.callbacks?.onOpenAgentPage(id),
          (id) => this.callbacks?.onHoverAgent(id),
        );
        this.sprites.set(v.agentId, sprite);
      }
    }
    for (const [id, sprite] of this.sprites) {
      if (!seen.has(id)) {
        sprite.destroy();
        this.sprites.delete(id);
      }
    }
  }

  setSelectedAgent(agentId: number | null) {
    for (const [id, sprite] of this.sprites) sprite.setSelected(id === agentId);
  }

  /** CSS-pixel position (relative to the canvas element's top-left) for
   * the DOM name label of one agent. Returns the above-the-bubbles anchor,
   * or the feet anchor with `below: true` when the label would leave the
   * canvas at the top — the only two placements the simplified avoidance
   * rules allow (redesign section 3.3 item 4). */
  getLabelAnchor(agentId: number): { x: number; y: number; below: boolean } | null {
    const s = this.sprites.get(agentId);
    if (!s) return null;
    const cam = this.cameras.main;
    const rect = this.game.canvas.getBoundingClientRect();
    const view = cam.worldView;
    if (view.width <= 0 || rect.width <= 0) return null;
    const toCss = (wx: number, wy: number) => ({
      x: (wx - view.x) * (rect.width / view.width),
      y: (wy - view.y) * (rect.height / view.height),
    });
    const head = s.labelAnchor();
    const above = toCss(head.x, head.y);
    if (above.y >= 30) return { ...above, below: false };
    const feet = s.feetAnchor();
    return { ...toCss(feet.x, feet.y), below: true };
  }

  /* ----------------------------------------------------------- handoffs -- */

  enqueueAssignment(a: AssignmentEvent) {
    if (this.assignmentQueue.some((q) => q.decisionId === a.decisionId)) return;
    this.assignmentQueue.push(a);
  }

  private processAssignments() {
    if (this.assignmentBusy || this.assignmentQueue.length === 0) return;
    const next = this.assignmentQueue.shift()!;
    const target = this.sprites.get(next.toAgentId);
    if (!target) return;
    const leader = next.fromAgentId != null ? this.sprites.get(next.fromAgentId) : undefined;
    target.showTalk(1100);
    if (!leader || leader.agentId === target.agentId) return;
    this.assignmentBusy = true;
    // Watchdog: never let a stuck walk block the queue forever.
    const watchdog = this.time.delayedCall(9000, () => {
      this.assignmentBusy = false;
    });
    const dest = nearestWalkable(target.desk.x, target.desk.y + 1);
    leader.walkToAndBack(dest, () => {
      leader.showTalk(950);
      target.showTalk(950);
    }, () => {
      watchdog.remove(false);
      this.assignmentBusy = false;
    });
  }

  update(time: number, delta: number) {
    for (const s of this.sprites.values()) s.update(time, delta);
    this.processAssignments();
  }
}
