type ArmPose =
  | "down" | "downLong" | "swingA" | "swingB"
  | "typeA" | "typeB" | "chin" | "paper" | "lap"
  | "up0" | "up1" | "up2" | "book";

function drawArmFront(ctx: Ctx, o: CharOpts, side: "l" | "r", pose: ArmPose) {
  const fem = o.female;
  const ax = side === "l" ? (fem ? 5 : 3) : (fem ? 23 : 24);
  const aw = fem ? 2 : 3;
  const T = o.top, D = o.topSh;
  switch (pose) {
    case "down":
      px(ctx, ax, 17, aw, 10, T); px(ctx, ax, 27, aw, 2, o.skin);
      px(ctx, side === "r" ? ax + aw - 1 : ax, 17, 1, 10, D);
      break;
    case "downLong":
      px(ctx, ax, 17, aw, 11, T); px(ctx, ax, 28, aw, 2, o.skin);
      break;
    case "swingA": // arm swung forward = drawn 1px longer on this side's stride
      px(ctx, ax, 17, aw, 11, T); px(ctx, ax, 28, aw, 2, o.skin);
      break;
    case "swingB":
      px(ctx, ax, 17, aw, 9, T); px(ctx, ax, 26, aw, 2, o.skin);
      break;
    case "chin": // forearm raised, hand beside the chin (front thinking)
      px(ctx, ax, 17, aw, 6, T);
      px(ctx, side === "l" ? ax + 1 : ax - 2, 14, 3, 3, T);
      px(ctx, side === "l" ? ax + 2 : ax - 3, 15, 3, 2, o.skin);
      break;
    case "book": // forearm bent inward, hand at the book's edge
      px(ctx, ax, 17, aw, 6, T);
      px(ctx, side === "l" ? ax + aw : ax - 4, 22, 4, 2, T);
      px(ctx, side === "l" ? ax + aw + 3 : ax - 5, 23, 2, 2, o.skin);
      break;
    default:
      px(ctx, ax, 17, aw, 10, T); px(ctx, ax, 27, aw, 2, o.skin);
  }
}

