      px(ctx, X(18), 10 + dy, 5, 5, H); px(ctx, X(18), 15 + dy, 4, 6, H); px(ctx, X(18), 21 + dy, 3, 4, H); // tail
      px(ctx, X(17), 9 + dy, 5, 2, D); // band
