export function ensureCharacterTextures(scene: Phaser.Scene, app: AgentAppearance) {
  const o = charOpts(app);
  for (const f of CHAR_FRAMES) {
    canvasTex(scene, charKey(app, f), 32, 40, (ctx) => {
      // Dark outline pass: the full silhouette painted in the outline
      // colour at the four neighbour offsets, then the character itself
      // on top — the single biggest readability trick in the reference
      // art (Pixel Agents / Metro City style).
      SILHOUETTE = OUTLINE;
      for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
        ctx.save();
        ctx.translate(1 + dx, 1 + dy);
        drawCharacter(ctx, o, f);
        ctx.restore();
      }
      SILHOUETTE = null;
      ctx.save();
      ctx.translate(1, 1);
      drawCharacter(ctx, o, f);
      ctx.restore();
    });
  }
}

