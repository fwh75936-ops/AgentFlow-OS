export function appearanceKey(app: AgentAppearance): string {
  return `${app.gender}-${app.skin}-${app.hair}-${app.outfit}`;
}
export function charKey(app: AgentAppearance, frame: CharFrame): string {
  return `char4-${appearanceKey(app)}-${frame}`;
}

interface CharOpts {
  female: boolean;
  skin: string; skinHi: string; skinSh: string; skinDeep: string;
  hair: string; hairSh: string; hairHi: string;
  top: string; topSh: string; topHi: string; accent: string;
  collar: OutfitCollar; accessory: OutfitAccessory;
  style: HairStyleKind;
  pants: string; pantsSh: string;
}

function charOpts(app: AgentAppearance): CharOpts {
  const base = skinBase(app.skin);
  const hd = hairDef(app.gender, app.hair);
  const od = outfitDef(app.outfit);
  const pants = app.outfit === 10 ? "#242424" : scale(od.top, 0.72);
  return {
    female: app.gender === "female",
    skin: base,
    skinHi: skinTone(base, 1.04, 4),
    skinSh: skinTone(base, 0.78),
    skinDeep: skinTone(base, 0.62),
    hair: hd.color, hairSh: scale(hd.color, 0.7), hairHi: mixWhite(hd.color, 0.22),
    top: od.top, topSh: scale(od.top, 0.76), topHi: mixWhite(od.top, 0.16),
    accent: od.accent,
    collar: od.collar, accessory: od.accessory,
    style: hd.style,
    pants, pantsSh: scale(pants, 0.8),
  };
}

/** Torso row profile [left, right] per y (17..29): narrower female
 * shoulders, a 1-2px waist pinch for both. */
function torsoRow(o: CharOpts, y: number): [number, number] {
  if (o.female) {
    if (y >= 24 && y <= 26) return [8, 21];
    return [7, 22];
  }
  if (y >= 24 && y <= 26) return [7, 22];
  return [6, 23];
}

/* ------------------------------------------------------------- head: front */

function hairBehindFront(ctx: Ctx, o: CharOpts) {
  const H = o.hair;
  if (o.style === "long") {
    px(ctx, 5, 5, 3, 18, H); px(ctx, 22, 5, 3, 17, H); // strands to the shoulders
    px(ctx, 5, 21, 3, 2, o.hairSh); px(ctx, 22, 20, 3, 2, o.hairSh); // stepped tips
  } else if (o.style === "ponytail") {
    px(ctx, 23, 7, 3, 15, H); // tail behind the right shoulder
    px(ctx, 23, 20, 2, 3, H);
    px(ctx, 22, 6, 3, 2, o.hairSh); // band
  }
}

function hairTopFront(ctx: Ctx, o: CharOpts) {
  const H = o.hair, D = o.hairSh, L = o.hairHi;
  switch (o.style) {
    case "short":
      px(ctx, 7, 2, 16, 2, H); px(ctx, 6, 3, 18, 2, H);
      px(ctx, 9, 2, 6, 1, L);
      px(ctx, 6, 5, 4, 2, H); px(ctx, 20, 5, 4, 1, H); // asymmetric fringe step
      px(ctx, 10, 5, 10, 1, D);
      break;
    case "sidepart":
      px(ctx, 7, 2, 16, 2, H); px(ctx, 6, 3, 18, 2, H);
      px(ctx, 13, 2, 5, 1, L);
      px(ctx, 11, 2, 1, 3, D); // the part groove
      px(ctx, 6, 5, 8, 2, H); px(ctx, 15, 5, 9, 1, H); // fringe sweeps one way
      break;
    case "buzz":
      px(ctx, 8, 2, 14, 1, H); px(ctx, 7, 3, 16, 1, H);
      px(ctx, 7, 4, 3, 1, H); px(ctx, 20, 4, 3, 1, H);
      px(ctx, 10, 3, 5, 1, L);
      break;
    case "curly":
      px(ctx, 7, 1, 4, 1, H); px(ctx, 12, 0, 5, 2, H); px(ctx, 18, 1, 4, 1, H);
      px(ctx, 6, 2, 18, 3, H);
      px(ctx, 9, 2, 4, 1, L);
      px(ctx, 6, 5, 3, 1, H); px(ctx, 11, 5, 3, 1, H); px(ctx, 16, 5, 3, 1, H); px(ctx, 21, 5, 3, 1, H); // scalloped edge
      px(ctx, 6, 4, 2, 3, H); px(ctx, 22, 4, 2, 3, H);
      break;
    case "long":
      px(ctx, 7, 2, 16, 2, H); px(ctx, 6, 3, 18, 2, H);
      px(ctx, 9, 2, 5, 1, L);
      px(ctx, 14, 3, 1, 2, D); // centre part
      px(ctx, 6, 5, 6, 1, H); px(ctx, 18, 5, 6, 1, H); // fringe leaves the forehead centre open
      break;
    case "bob":
      px(ctx, 6, 2, 18, 3, H);
      px(ctx, 9, 2, 6, 1, L);
      px(ctx, 8, 5, 14, 2, H); // straight fringe to the brows
      px(ctx, 6, 5, 2, 11, H); px(ctx, 22, 5, 2, 11, H); // sides to the chin
      px(ctx, 6, 15, 2, 1, D); px(ctx, 22, 15, 2, 1, D);
      break;
    case "bun":
      px(ctx, 12, 0, 6, 2, H); px(ctx, 13, 0, 3, 1, L); // the bun
      px(ctx, 12, 2, 6, 1, D);
      px(ctx, 7, 2, 16, 2, H); px(ctx, 6, 3, 18, 2, H);
      px(ctx, 7, 5, 16, 1, H);
      px(ctx, 10, 5, 9, 1, D);
      break;
    case "ponytail":
      px(ctx, 7, 2, 16, 2, H); px(ctx, 6, 3, 18, 2, H);
      px(ctx, 9, 2, 6, 1, L);
      px(ctx, 7, 5, 16, 1, H);
      px(ctx, 10, 5, 9, 1, D);
      break;
  }
}

function drawGlassesFront(ctx: Ctx) {
  const F = "#343632";
  // left lens outline (5x4) + right lens + bridge; drawn as 1px rects
  for (const x0 of [9, 17]) {
    px(ctx, x0, 9, 5, 1, F); px(ctx, x0, 12, 5, 1, F);
    px(ctx, x0, 10, 1, 2, F); px(ctx, x0 + 4, 10, 1, 2, F);
  }
  px(ctx, 14, 10, 3, 1, F);
}
function drawHeadphonesFront(ctx: Ctx, o: CharOpts) {
  const B = "#343632";
  px(ctx, 6, 10, 2, 3, B); px(ctx, 22, 10, 2, 3, B); // small ear cups
  px(ctx, 6, 11, 1, 1, o.accent); px(ctx, 23, 11, 1, 1, o.accent);
}

function drawHeadFront(ctx: Ctx, o: CharOpts, dy = 0) {
  hairBehindFront(ctx, o);
  px(ctx, 8, 4 + dy, 15, 13, o.skin); // face block
  px(ctx, 9, 4 + dy, 4, 1, o.skinHi); // forehead light
  if (o.style !== "bob") { px(ctx, 7, 9 + dy, 1, 3, o.skin); px(ctx, 23, 9 + dy, 1, 3, o.skin); } // ears
  hairTopFront(ctx, o);
  if (dy) { // slumped: hair hangs 1px lower over the face
    px(ctx, 7, 6, 16, 1, o.hair);
  }
  const eye = "#2B2622";
  px(ctx, 10, 10 + dy, 2, 2, eye); px(ctx, 19, 10 + dy, 2, 2, eye);
  px(ctx, 10, 9 + dy, 2, 1, o.hairSh); px(ctx, 19, 9 + dy, 2, 1, o.hairSh); // brows
  px(ctx, 14, 12 + dy, 1, 2, o.skinSh); // nose shadow
  px(ctx, 13, 14 + dy, 4, 1, "#B0714F"); // mouth
  px(ctx, 10, 16 + dy, 11, 1, o.skinSh); // jaw shade
  if (o.accessory === "glasses" && !SILHOUETTE) drawGlassesFront(ctx);
  if (o.accessory === "headphones" && !SILHOUETTE) drawHeadphonesFront(ctx, o);
}

