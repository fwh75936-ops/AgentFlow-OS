/** This file draws ONLY the functional sprites: the characters and the
 * status bubbles. Characters are baked on a 32x40 canvas from the shared
 * appearance contract (gender/skin/hair/outfit — see docs/APPEARANCE.md)
 * and status is shown with drawn pixel icons instead of text glyphs.
 * The office ENVIRONMENT is not drawn here at all: it is a single
 * painted backdrop (src/assets/office-bg-gpt.png, generated by the
 * user's GPT image model from the user's reference illustration) whose
 * grid calibration lives in OfficeMap. There is NO text anywhere in the
 * scene: zones read from the painting's layout + furniture, names live
 * in a DOM overlay owned by the React layer. */

type Ctx = CanvasRenderingContext2D;
/** When set, every px() call paints this colour instead — used to render
 * a character's silhouette for its dark outline pass. */
let SILHOUETTE: string | null = null;
const OUTLINE = "#343632";
function px(ctx: Ctx, x: number, y: number, w: number, h: number, color: string) {
  ctx.fillStyle = SILHOUETTE ?? color;
  ctx.fillRect(x, y, w, h);
}

function canvasTex(scene: Phaser.Scene, key: string, w: number, h: number, draw: (ctx: Ctx) => void) {
  if (scene.textures.exists(key)) return key;
  const tex = scene.textures.createCanvas(key, w, h);
  if (!tex) return key;
  const ctx = tex.getContext();
  ctx.clearRect(0, 0, w, h);
  draw(ctx);
  tex.refresh();
  return key;
}

/* ------------------------------------------------------------ colour utils */

function rgb(hex: string): [number, number, number] {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}
function toHex(r: number, g: number, b: number): string {
  const c = (v: number) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, "0");
  return `#${c(r)}${c(g)}${c(b)}`;
}
/** Multiply brightness (f < 1 darkens). */
function scale(hex: string, f: number): string {
  const [r, g, b] = rgb(hex);
  return toHex(r * f, g * f, b * f);
}
/** Mix toward white by amt (0..1). */
function mixWhite(hex: string, amt: number): string {
  const [r, g, b] = rgb(hex);
  return toHex(r + (255 - r) * amt, g + (255 - g) * amt, b + (255 - b) * amt);
}
/** Skin derivation per the redesign spec: highlight = c*1.04+4,
 * shadow = c*0.78, deep shadow = c*0.62. */
function skinTone(hex: string, f: number, add = 0): string {
  const [r, g, b] = rgb(hex);
  return toHex(r * f + add, g * f + add, b * f + add);
}


